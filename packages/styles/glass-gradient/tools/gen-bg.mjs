// Pre-render the glass-gradient background (three soft colour blobs) as tiny WebP images, one per aspect,
// and embed them in pack.css (between the bg:start / bg:end markers) as data URIs. A bitmap scaled up by the browser costs a fraction of painting
// full-frame CSS radial gradients on every frame (measured, see docs/reports/M3.md).
// Usage (repo root): node packages/styles/glass-gradient/tools/gen-bg.mjs
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const packDir = join(import.meta.dirname, "..");
const tokens = JSON.parse(readFileSync(join(packDir, "tokens.json"), "utf8"));
const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const bg = hex(tokens.colors.bg);
// Blob centres / radii as fractions of the frame (x, y, r relative to the longer side).
const BLOBS = [
  { c: hex(tokens.colors.blob1), x: 0.15, y: 0.1, r: 0.45 },
  { c: hex(tokens.colors.blob2), x: 0.95, y: 0.45, r: 0.4 },
  { c: hex(tokens.colors.blob3), x: 0.3, y: 1.0, r: 0.5 },
];
const SIZES = { "16x9": [192, 108], "9x16": [108, 192], "1x1": [128, 128], "4x5": [120, 150] };
const work = mkdtempSync(join(tmpdir(), "glass-bg-"));
let css = "/* bg:start — generated by tools/gen-bg.mjs, do not edit by hand */\n";
for (const [slug, [w, h]] of Object.entries(SIZES)) {
  const long = Math.max(w, h);
  const px = Buffer.alloc(w * h * 3);
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      let [r, g, b] = bg;
      for (const k of BLOBS) {
        const d = Math.hypot(x - k.x * w, y - k.y * h) / (k.r * long);
        const a = 0.85 * Math.max(0, 1 - d / 0.7) ** 1.6; // same falloff as "0% -> transparent 70%"
        r = r * (1 - a) + k.c[0] * a;
        g = g * (1 - a) + k.c[1] * a;
        b = b * (1 - a) + k.c[2] * a;
      }
      px.set([r, g, b].map(Math.round), (y * w + x) * 3);
    }
  const ppm = join(work, `${slug}.ppm`);
  writeFileSync(ppm, Buffer.concat([Buffer.from(`P6\n${w} ${h}\n255\n`), px]));
  const webp = join(work, `${slug}.webp`);
  execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", ppm, "-quality", "90", webp]);
  css += `.a-${slug} .blobs {\n  background-image: url("data:image/webp;base64,${readFileSync(webp).toString("base64")}");\n}\n`;
}
css += "/* bg:end */\n";
const cssFile = join(packDir, "pack.css");
const pack = readFileSync(cssFile, "utf8");
const block = /\/\* bg:start[\s\S]*?\/\* bg:end \*\/\n/;
writeFileSync(cssFile, block.test(pack) ? pack.replace(block, css) : `${pack}\n${css}`);
console.log(`pack.css background block written (${css.length} bytes)`);
