// M0 spike: generate a 10 s GSAP composition with Vietnamese text for 16:9 and 9:16.
// Throwaway code. Not imported by product code.
import { cpSync, mkdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

export type Aspect = "16x9" | "9x16";
export const SIZES: Record<Aspect, { w: number; h: number }> = {
  "16x9": { w: 1920, h: 1080 },
  "9x16": { w: 1080, h: 1920 },
};

const TITLE = "Ẩn Ỹ Ự — Tiếng Việt có dấu đầy đủ";
const SUBTITLE = "Lãi kép: tiền đẻ ra tiền, mỗi năm một nhiều hơn";
const BULLETS = ["Gửi 10 triệu đồng", "Lãi suất 8% mỗi năm", "Sau 10 năm: 21,6 triệu"];
const BARS = [10, 10.8, 11.7, 12.6, 13.6, 14.7, 15.9, 17.1, 18.5, 20, 21.6];

const root = new URL(".", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

function words(text: string, cls: string): string {
  // Split on spaces only: each Vietnamese syllable keeps its diacritics intact (NFC).
  return text
    .normalize("NFC")
    .split(" ")
    .map((w, i) => `<span class="${cls}" id="${cls}-${i}">${w}</span>`)
    .join(" ");
}

export function buildProject(aspect: Aspect, outDir: string): string {
  const { w, h } = SIZES[aspect];
  const vertical = aspect === "9x16";
  const dir = join(outDir, `project-${aspect}`);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, "assets", "fonts"), { recursive: true });
  mkdirSync(join(dir, "assets", "vendor"), { recursive: true });

  const fontDir = join(root, "node_modules", "@fontsource", "be-vietnam-pro", "files");
  for (const f of [
    "be-vietnam-pro-vietnamese-400-normal.woff2",
    "be-vietnam-pro-vietnamese-800-normal.woff2",
    "be-vietnam-pro-latin-400-normal.woff2",
    "be-vietnam-pro-latin-800-normal.woff2",
    "be-vietnam-pro-latin-ext-400-normal.woff2",
    "be-vietnam-pro-latin-ext-800-normal.woff2",
  ]) {
    cpSync(join(fontDir, f), join(dir, "assets", "fonts", f));
  }
  // GSAP bundled locally: HyperFrames keeps a local gsap <script src> that exists on disk.
  cpSync(join(root, "node_modules", "gsap", "dist", "gsap.min.js"), join(dir, "assets", "vendor", "gsap", "dist", "gsap.min.js"), {
    recursive: true,
  });
  // Pinned HyperFrames runtime served locally so the browser preview never pulls it from a CDN.
  cpSync(
    join(root, "node_modules", "@hyperframes", "core", "dist", "hyperframe.runtime.iife.js"),
    join(dir, "assets", "vendor", "hyperframe.runtime.iife.js"),
  );

  // Deterministic background music bed (10 s) generated by FFmpeg, for audio-seam checks.
  const music = join(dir, "assets", "bed.wav");
  execFileSync("ffmpeg", [
    "-y", "-loglevel", "error",
    "-f", "lavfi", "-i", "sine=frequency=220:sample_rate=48000:duration=10",
    "-f", "lavfi", "-i", "sine=frequency=330:sample_rate=48000:duration=10",
    "-filter_complex", "[0][1]amix=inputs=2,volume=0.25,afade=t=in:d=0.5,afade=t=out:st=9.3:d=0.7",
    "-ac", "2", music,
  ]);

  const titleSize = vertical ? 96 : 104;
  const pad = vertical ? 96 : 140;
  const chartH = vertical ? 620 : 420;
  const barW = vertical ? 64 : 72;
  const fontFaces = [400, 800]
    .flatMap((wt) =>
      ["vietnamese", "latin-ext", "latin"].map(
        (sub) =>
          `@font-face{font-family:"Be Vietnam Pro";font-weight:${wt};font-style:normal;src:url("assets/fonts/be-vietnam-pro-${sub}-${wt}-normal.woff2") format("woff2");}`,
      ),
    )
    .join("\n");

  const bars = BARS.map(
    (v, i) =>
      `<div class="bar" id="bar-${i}" style="height:${Math.round((v / 22) * chartH)}px;width:${barW}px"></div>`,
  ).join("");

  const html = `<!doctype html>
<html lang="vi">
<head>
<meta charset="utf-8">
<style>
${fontFaces}
html,body{margin:0;background:#0b1020;}
#root{position:relative;width:${w}px;height:${h}px;overflow:hidden;font-family:"Be Vietnam Pro",sans-serif;color:#f4f6fb;background:linear-gradient(160deg,#0b1020 0%,#16213e 60%,#1b2a5a 100%);}
.bg{position:absolute;inset:0;}
.dot{position:absolute;width:10px;height:10px;border-radius:50%;background:#4cc9f0;opacity:.35;}
#scene-title{position:absolute;inset:0;display:flex;flex-direction:column;justify-content:center;padding:0 ${pad}px;box-sizing:border-box;}
#title{font-weight:800;font-size:${titleSize}px;line-height:1.15;margin:0;text-wrap:balance;}
.tw{display:inline-block;}
#subtitle{font-weight:400;font-size:${Math.round(titleSize * 0.42)}px;margin-top:32px;color:#b8c4e0;}
#scene-data{position:absolute;inset:0;padding:${vertical ? "260px" : "120px"} ${pad}px;box-sizing:border-box;display:flex;flex-direction:${vertical ? "column" : "row"};gap:${vertical ? 80 : 120}px;align-items:${vertical ? "stretch" : "center"};}
#bullets{flex:${vertical ? 1 : 1.25};display:flex;flex-direction:column;gap:28px;justify-content:center;}
.bullet{font-size:${vertical ? 58 : 48}px;font-weight:800;text-wrap:balance;}
.bullet b{color:#4cc9f0;}
#chart{flex:1;display:flex;align-items:flex-end;gap:${vertical ? 14 : 16}px;height:${chartH}px;}
.bar{background:linear-gradient(180deg,#4cc9f0,#4361ee);border-radius:10px 10px 0 0;transform-origin:50% 100%;}
#counter{position:absolute;right:${pad}px;${vertical ? "top:800px" : "top:110px"};font-size:${vertical ? 120 : 110}px;font-weight:800;color:#ffd166;}
</style>
</head>
<body>
<div id="root" data-composition-id="main" data-start="0" data-duration="10" data-width="${w}" data-height="${h}">
  <audio id="bed" src="assets/bed.wav" data-start="0" data-duration="10" data-volume="1"></audio>
  <div class="bg" id="bg"></div>
  <div id="scene-title" class="clip" data-start="0" data-duration="4.6">
    <h1 id="title">${words(TITLE, "tw")}</h1>
    <div id="subtitle">${SUBTITLE.normalize("NFC")}</div>
  </div>
  <div id="scene-data" class="clip" data-start="4.6" data-duration="5.4">
    <div id="bullets">${BULLETS.map((b, i) => `<div class="bullet" id="bl-${i}"><b>•</b> ${b.normalize("NFC")}</div>`).join("")}</div>
    <div id="chart">${bars}</div>
    <div id="counter"><span id="counter-v">10,0</span> tr</div>
  </div>
</div>
<script src="assets/vendor/gsap/dist/gsap.min.js"></script>
<script src="assets/vendor/hyperframe.runtime.iife.js"></script>
<script>
(function(){
  // Seeded PRNG (mulberry32): no Math.random.
  function mulberry32(a){return function(){a|=0;a=a+0x6D2B79F5|0;var t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296;};}
  var rnd = mulberry32(20261112);
  var bg = document.getElementById("bg");
  var dots = [];
  for (var i=0;i<28;i++){var d=document.createElement("div");d.className="dot";d.id="dot-"+i;d.style.left=(rnd()*${w})+"px";d.style.top=(rnd()*${h})+"px";bg.appendChild(d);dots.push(d);}
  var tl = gsap.timeline({ paused: true });
  dots.forEach(function(d,i){ tl.fromTo(d,{y:0},{y:-(60+rnd()*140),duration:10,ease:"none"},0); });
  tl.fromTo(".tw",{opacity:0,y:60},{opacity:1,y:0,duration:0.6,ease:"power3.out",stagger:0.12},0.2);
  tl.fromTo("#subtitle",{opacity:0,y:30},{opacity:1,y:0,duration:0.6,ease:"power2.out"},1.6);
  tl.fromTo("#title",{scale:1},{scale:1.04,duration:2,ease:"sine.inOut"},2.4);
  tl.fromTo(".bullet",{opacity:0,x:-60},{opacity:1,x:0,duration:0.5,ease:"power3.out",stagger:0.45},4.8);
  tl.fromTo(".bar",{scaleY:0},{scaleY:1,duration:0.6,ease:"back.out(1.6)",stagger:0.12},5.2);
  var c = {v:10};
  tl.fromTo(c,{v:10},{v:21.6,duration:2.6,ease:"power1.inOut",onUpdate:function(){document.getElementById("counter-v").textContent=c.v.toFixed(1).replace(".",",");}},5.4);
  tl.fromTo("#counter",{opacity:0,scale:0.6},{opacity:1,scale:1,duration:0.5,ease:"back.out(2)"},5.2);
  window.__timelines = window.__timelines || {};
  window.__timelines["main"] = tl;
})();
</script>
</body>
</html>
`;
  writeFileSync(join(dir, "index.html"), html, "utf8");
  return dir;
}

if (process.argv[1] && process.argv[1].endsWith("gen.ts")) {
  const out = join(root, "output");
  if (!existsSync(out)) mkdirSync(out, { recursive: true });
  for (const a of Object.keys(SIZES) as Aspect[]) console.log(buildProject(a, out));
}
